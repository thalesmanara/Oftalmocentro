=SELECT
  dv.id,
  dv.document_id AS "documentId",
  dv.version_number AS "versionNumber",
  dv.is_current AS "isCurrent",
  dv.status,
  COALESCE(dv.original_file_name, dv.file_name) AS "fileName",
  dv.original_file_name AS "originalFileName",
  dv.file_size AS "fileSize",
  COALESCE(dv.detected_mime_type, dv.mime_type) AS "mimeType",
  dv.detected_mime_type AS "detectedMimeType",
  dv.browser_mime_type AS "browserMimeType",
  dv.file_extension AS "fileExtension",
  dv.title_snapshot AS "titleSnapshot",
  dv.description_snapshot AS "descriptionSnapshot",
  dv.expiration_date AS "expirationDate",
  dv.processing_status AS "processingStatus",
  dv.validation_status AS "validationStatus",
  dv.validation_error_code AS "validationErrorCode",
  dv.validated_at AS "validatedAt",
  dv.page_count AS "pageCount",
  LEFT(dv.checksum, 64) AS "checksum",
  dv.checksum_algorithm AS "checksumAlgorithm",
  dv.created_by AS "createdBy",
  u.name AS "createdByName",
  dv.created_at AS "createdAt",
  dv.ocr_status AS "ocrStatus",
  dv.ocr_engine AS "ocrEngine",
  dv.ocr_languages AS "ocrLanguages",
  dv.ocr_attempts AS "ocrAttempts",
  dv.ocr_error_code AS "ocrErrorCode",
  dv.ocr_started_at AS "ocrStartedAt",
  dv.ocr_finished_at AS "ocrFinishedAt",
  dv.ocr_duration_ms AS "ocrDurationMs",
  dv.extraction_method AS "extractionMethod",
  dv.ocr_derived_file_name AS "ocrDerivedFileName",
  dv.ocr_page_count AS "ocrPageCount",
  (dv.ocr_derived_file_path IS NOT NULL) AS "hasOcrDerivedFile",
  dv.ocr_quality_score AS "ocrQualityScore",
  dv.ocr_quality_grade AS "ocrQualityGrade",
  dv.ocr_word_count AS "ocrWordCount",
  dv.ocr_unique_word_count AS "ocrUniqueWordCount",
  dv.ocr_character_count AS "ocrCharacterCount",
  dv.ocr_characters_per_page AS "ocrCharactersPerPage",
  dv.ocr_quality_reason AS "ocrQualityReason",
  dv.ocr_review_reason AS "ocrReviewReason",
  dv.ocr_mode AS "ocrMode",
  dv.sheet_count AS "sheetCount",
  dv.table_row_count AS "tableRowCount",
  dv.table_column_count AS "tableColumnCount",
  dv.table_summary AS "tableSummary",
  (dv.table_preview IS NOT NULL) AS "hasTablePreview"
FROM document_versions dv
JOIN documents d ON d.id = dv.document_id AND d.deleted_at IS NULL
LEFT JOIN users u ON u.id = dv.created_by
WHERE dv.document_id = '{{ $json.query.documentId }}'::uuid
ORDER BY dv.version_number DESC;